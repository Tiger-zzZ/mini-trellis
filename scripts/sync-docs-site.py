#!/usr/bin/env python3
"""Render the canonical Markdown guides into an existing website checkout.

Uses only the Python standard library. Writes explicit guide/asset paths; it
does not delete files, invoke Git, build, or publish. --check is read-only.
"""

import argparse
import json
import re
from pathlib import Path
from urllib.parse import urlsplit, unquote


ROOT = Path(__file__).resolve().parents[1]
REPO_URL = "https://github.com/Tiger-zzZ/mini-trellis/blob/main/"
GROUPS = [
    ("Start here", "开始使用", ["index", "install", "how-it-works", "scenarios"]),
    ("Guides", "使用指南", ["using", "writing-notes", "history", "recall"]),
    ("Reference", "参考", ["agents", "commands", "configuration"]),
    ("Maintenance", "维护与支持", ["migration", "upgrade", "faq", "troubleshooting"]),
    ("Project", "项目", ["benchmarks", "contributing"]),
]


def page_source(name, lang):
    suffix = "_CN" if lang == "zh" else ""
    if name == "contributing":
        return ROOT / f"CONTRIBUTING{suffix}.md"
    return ROOT / "docs" / f"{name}{suffix}.md"


def page_url(name, lang):
    slug = "docs" if name == "index" else name
    return ("/zh" if lang == "zh" else "") + f"/{slug}/"


def render_outputs(site):
    pages = [n for _, _, names in GROUPS for n in names]
    mapping = {
        page_source(n, lang).resolve(): page_url(n, lang)
        for lang in ("en", "zh") for n in pages
    }
    mapping.update({ROOT / "README.md": "/", ROOT / "README_CN.md": "/zh/"})
    mapping[ROOT / "CHANGELOG.md"] = "/releases/"
    outputs = {}
    navigation = {}
    for lang in ("en", "zh"):
        nav = []
        for group_en, group_zh, names in GROUPS:
            items = []
            for name in names:
                source = page_source(name, lang)
                body = source.read_text(encoding="utf-8")
                title = re.search(r"^# (.+)$", body, re.M).group(1)

                def rewrite(match):
                    target = match.group(1)
                    parts = urlsplit(target)
                    if parts.scheme or parts.netloc or not parts.path or target.startswith("/"):
                        return match.group(0)
                    resolved = (source.parent / unquote(parts.path)).resolve()
                    if not resolved.is_relative_to(ROOT):
                        raise ValueError(f"Link escapes repository: {source}: {target}")
                    if not resolved.exists():
                        raise ValueError(f"Missing link target: {source}: {target}")
                    if resolved == ROOT / "CHANGELOG.md":
                        dest = ("/zh" if lang == "zh" else "") + "/releases/"
                    elif resolved in mapping:
                        dest = mapping[resolved]
                    elif resolved.is_relative_to(ROOT / "docs" / "assets"):
                        dest = "/assets/" + resolved.name
                    elif resolved.is_relative_to(ROOT / "docs" / "releases"):
                        translated = site / "zh" / "releases" / resolved.name
                        prefix = "/zh" if lang == "zh" and translated.exists() else ""
                        dest = prefix + "/releases/" + resolved.stem + "/"
                    else:
                        dest = REPO_URL + resolved.relative_to(ROOT).as_posix()
                    if parts.fragment:
                        dest += "#" + parts.fragment
                    return "](" + dest + ")"

                body = re.sub(r"\]\(([^\s)]+)\)", rewrite, body)
                slug = "docs" if name == "index" else name
                dest = (Path("zh") if lang == "zh" else Path()) / f"{slug}.md"
                meta = {
                    "layout": "default", "title": title, "lang": lang,
                    "permalink": page_url(name, lang),
                    "lang_peer": page_url(name, "en" if lang == "zh" else "zh"),
                    "group": group_zh if lang == "zh" else group_en,
                    "source_path": source.relative_to(ROOT).as_posix(),
                }
                front = "---\n" + "\n".join(f"{k}: {json.dumps(v, ensure_ascii=False)}" for k, v in meta.items())
                outputs[dest] = (front + "\n---\n<!-- Generated by scripts/sync-docs-site.py in mini-trellis. Edit source_path. -->\n\n" + body).encode()
                items.append({"title": title, "url": page_url(name, lang)})
            nav.append({"title": group_zh if lang == "zh" else group_en, "items": items})
        nav[-1]["items"].append({"title": "版本记录" if lang == "zh" else "Releases", "url": ("/zh" if lang == "zh" else "") + "/releases/"})
        navigation[lang] = nav
    version = json.loads((ROOT / "packages/cli/package.json").read_text())["version"]
    for path, data in [("_data/navigation.json", navigation), ("_data/docs.json", {"version": version, "source_repository": REPO_URL})]:
        outputs[Path(path)] = (json.dumps(data, ensure_ascii=False, indent=2) + "\n").encode()
    for asset in sorted((ROOT / "docs/assets").glob("*.svg")):
        outputs[Path("assets") / asset.name] = asset.read_bytes()
    outputs[Path("assets/favicon.svg")] = (ROOT / "docs/assets/logo.svg").read_bytes()
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--site", type=Path, required=True, help="Existing mini-trellis website checkout")
    parser.add_argument("--check", action="store_true", help="Report differences without writing")
    args = parser.parse_args()
    site = args.site.resolve()
    if site == ROOT or not (site / "_config.yml").is_file():
        parser.error("--site must point to the separate website checkout containing _config.yml")
    outputs = render_outputs(site)
    changed = [p for p, data in outputs.items() if not (site / p).is_file() or (site / p).read_bytes() != data]
    if args.check:
        for path in changed:
            print(f"Out of sync: {path}")
        print(f"Checked {len(outputs)} generated files; {len(changed)} differ.")
        return bool(changed)
    for path in changed:
        (site / path).parent.mkdir(parents=True, exist_ok=True)
        (site / path).write_bytes(outputs[path])
    print(f"Updated {len(changed)} of {len(outputs)} generated files in {site}.")
    return False


if __name__ == "__main__":
    raise SystemExit(main())
